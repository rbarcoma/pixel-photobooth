import {existsSync} from 'node:fs';
import {readFile,writeFile} from 'node:fs/promises';
import {randomBytes} from 'node:crypto';
import {spawnSync} from 'node:child_process';

const secret=()=>randomBytes(32).toString('hex');
if(!existsSync('.env.local')){
 const password=secret();
 await writeFile('.env.local',`# Local development only; generated by npm run setup:local.\nDATABASE_URL=mysql://pixel_booth:${password}@127.0.0.1:3307/pixel_booth\nPHOTO_STORAGE=local\nPHOTO_DIRECTORY=server/data/photos\nMYSQL_PORT=3307\nMYSQL_PASSWORD=${password}\nMYSQL_ROOT_PASSWORD=${secret()}\nSESSION_SECRET=${secret()}\nADMIN_API_TOKEN=${secret()}\nCRON_SECRET=${secret()}\nAPP_ORIGIN=http://localhost:5173\nFEEDBACK_MODERATION=auto\nPORT=3001\n`,{mode:0o600,flag:'wx'});
 console.log('Created ignored .env.local with independent local credentials.');
}
const contents=await readFile('.env.local','utf8');
if(!/^DATABASE_URL=mysql:\/\//m.test(contents)||!/^MYSQL_PASSWORD=.+/m.test(contents)||!/^MYSQL_ROOT_PASSWORD=.+/m.test(contents)){
 throw Error('Existing .env.local was preserved. Configure it for MySQL using LOCAL_SETUP.md, or run npm run db:migrate for your existing database.');
}
function run(command,args){
 const child=spawnSync(command,args,{stdio:'inherit'});
 if(child.error)throw child.error;
 if(child.status!==0)process.exit(child.status||1);
}
run('docker',['compose','--env-file','.env.local','up','-d','--wait','mysql']);
run(process.execPath,['--env-file-if-exists=.env','--env-file=.env.local','--import','tsx','scripts/migrate.ts']);
console.log('Local MySQL is ready. Start the app with npm run dev.');
